r"""Lists every literal that approximates pi or 1/3 inside this node's own `## Line map`
ranges of the Fortran source, and writes the list to `ExactConstantLiterals.generated.txt`
(this node's BOOT.md, "## Corrected model", "`ExactConstants`": "The site list is generated").

The ranges are the ones `classify-real4-accumulators.py` reads from the scope sentence of
`## Line map` (not a second copy of the four numbers); the statement joiner and the range
reader are that script's own, imported, not reimplemented. A literal approximates pi or 1/3
when it matches one of the patterns of `ACCEPTANCE.md`: `3\.14\d*` (the sphere volume's
`3.14159`, `VM`'s `3.14`), `12\.566\d*` (the solid angle, 4 pi), `0?\.333\d*`, or the quotient
`1/3.` not preceded by a letter, digit or point (line 501's exponent). A number that is
exact written as a real (`3.`, `6.`, `2.`) approximates nothing and is not listed.

What is deliberately not generated: what the port does at each listed line (reproduced under
the flag, not ported, unchanged for a reason, replaced whole by `BridgeFrustum`). That
correspondence is the hand-written `ExactConstantSites.txt` beside this file, checked against
this list both ways by `tests/Particle.Tests/ExactConstantSiteTests.cs`.

Python 3.8+, standard library only.

    python scan-exact-constants.py scan [--source PATH]  # the list on stdout; PATH replaces the original's source
    python scan-exact-constants.py generate              # (re)writes ExactConstantLiterals.generated.txt
    python scan-exact-constants.py verify                # regenerates, fails on any byte difference
"""

from __future__ import annotations

import importlib.util
import re
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

NODE_ROOT = Path(__file__).resolve().parent
OUTPUT_PATH = NODE_ROOT / "ExactConstantLiterals.generated.txt"
SCRIPT_NAME = "scan-exact-constants.py"

# The patterns of ACCEPTANCE.md, "ExactConstants at this node's sites".
PATTERNS = (
    re.compile(r"3\.14\d*"),
    re.compile(r"12\.566\d*"),
    re.compile(r"0?\.333\d*"),
    re.compile(r"(?<![A-Za-z0-9.])1/3\."),
)


def load_classifier():
    """`classify-real4-accumulators.py` as a module: its scope-sentence reader and its
    logical-statement builder are the ones this scan uses."""
    path = NODE_ROOT / "classify-real4-accumulators.py"
    spec = importlib.util.spec_from_file_location("classify_real4_accumulators", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def literals_of(statement: str) -> Dict[str, int]:
    """Literal text (lower case) -> occurrences in one statement."""
    text = statement.lower()
    found: Dict[str, int] = {}
    for pattern in PATTERNS:
        for match in pattern.finditer(text):
            found[match.group(0)] = found.get(match.group(0), 0) + 1
    return found


def scan(source_lines: List[str], ranges: List[Tuple[int, int]], classifier) -> List[Tuple[int, str, int]]:
    rows: List[Tuple[int, str, int]] = []
    for line_no, text in classifier.build_logical_statements(source_lines, ranges):
        for literal, count in sorted(literals_of(text).items()):
            rows.append((line_no, literal, count))
    return rows


def render(rows: List[Tuple[int, str, int]]) -> str:
    lines = [
        "# Generated by scan-exact-constants.py by scanning this node's own Fortran Line map",
        "# ranges (BOOT.md, '## Line map') for every match of 3.14*, 12.566*, 0?.333* and of the",
        "# quotient 1/3. (ACCEPTANCE.md, 'ExactConstants'). Do not edit by",
        "# hand: `python scan-exact-constants.py verify` regenerates this file and fails if it",
        "# differs (BOOT.md, '## Corrected model', 'ExactConstants'). What the port does at each",
        "# line is ExactConstantSites.txt's own hand-written correspondence, not this file's.",
        "#",
        "# fortran line (first physical line of the statement) | literal as written | occurrences",
    ]
    for line_no, literal, count in rows:
        lines.append(f"{line_no} | {literal} | {count}")
    return "\n".join(lines) + "\n"


def parse_arguments(argv: List[str]) -> Tuple[Optional[str], Optional[Path]]:
    if not argv or argv[0] not in ("scan", "generate", "verify"):
        return None, None
    if len(argv) == 1:
        return argv[0], None
    if argv[0] == "scan" and len(argv) == 3 and argv[1] == "--source":
        return "scan", Path(argv[2])
    return None, None


def main(argv: List[str]) -> int:
    command, source = parse_arguments(argv)
    if command is None:
        print(f"usage: {SCRIPT_NAME} scan [--source PATH] | generate | verify", file=sys.stderr)
        return 2

    classifier = load_classifier()
    if source is None:
        classifier.verify_no_implicit_statement()
        source_lines = classifier.read_source_lines()
    else:
        source_lines = source.read_text(encoding="utf-8").splitlines()
    text = render(scan(source_lines, classifier.parse_line_map_ranges(), classifier))

    if command == "scan":
        sys.stdout.write(text)
    elif command == "generate":
        OUTPUT_PATH.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT_PATH}")
    else:
        if not OUTPUT_PATH.is_file():
            raise SystemExit(f"verify: {OUTPUT_PATH} is not committed")
        if text != OUTPUT_PATH.read_text(encoding="utf-8"):
            with tempfile.NamedTemporaryFile(
                mode="w", suffix=".txt", prefix="propstruct_exact_constants_", delete=False, encoding="utf-8"
            ) as handle:
                handle.write(text)
                tmp_path = handle.name
            raise SystemExit(f"verify: {OUTPUT_PATH} does not reproduce byte for byte on regeneration (see {tmp_path})")
        rows = sum(1 for line in text.splitlines() if line and not line.startswith("#"))
        print(f"verify: {OUTPUT_PATH.name} reproduces byte for byte ({rows} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
